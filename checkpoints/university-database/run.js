// Runs the SQL files on a temporary MySQL server and saves every result in results.md
// Run with: npm start   (the first run downloads MySQL, which takes a minute or two)
//
// You can also run the .sql files yourself in MySQL Workbench or the mysql CLI,
// in order: 01_schema.sql, 02_data.sql, 03_queries.sql (and 04 to see the errors).

const fs = require('fs');
const path = require('path');
const mysql = require('mysql2/promise');
const { createDB } = require('mysql-memory-server');

const FILES = ['01_schema.sql', '02_data.sql', '03_queries.sql', '04_constraint_tests.sql'];

// Split a .sql file into statements. A statement ends with ";" at the end of a
// line (a "-- comment" may follow it). Labels come from "-- Query/Check/Test ..."
// comments, and "-- expect: CODE" says which error a test must produce.
function statements(sql) {
  return sql
    .split(/;[ \t]*(?:--[^\n]*)?$/m)
    .map((chunk) => {
      const lines = chunk.trim().split('\n');
      const comments = lines.filter((l) => l.trim().startsWith('--')).map((l) => l.replace(/^\s*--\s*/, ''));
      const code = lines.filter((l) => !l.trim().startsWith('--')).join('\n').trim();
      const labels = comments.filter((c) => /^(Query|Check|Test)\b/.test(c));
      const expect = comments.find((c) => c.startsWith('expect:'))?.slice(7).trim();
      return { label: labels[labels.length - 1] || '', expect, code };
    })
    .filter((s) => s.code);
}

function markdownTable(rows) {
  if (rows.length === 0) return '_(no rows)_';
  const cols = Object.keys(rows[0]);
  const cell = (v) => (v === null ? 'NULL' : v instanceof Date ? v.toISOString().slice(0, 10) : String(v));
  return [
    `| ${cols.join(' | ')} |`,
    `| ${cols.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${cols.map((c) => cell(r[c])).join(' | ')} |`),
  ].join('\n');
}

// checkpoint.sql = steps 1 to 3 in one file, ready to paste into MySQL Workbench
function writeCheckpointFile() {
  const parts = FILES.slice(0, 3).map((f) => fs.readFileSync(path.join(__dirname, 'sql', f), 'utf8').trim());
  const header = '-- University database checkpoint (MySQL 8+)\n-- Steps 1 to 4 in one file. Generated from the sql/ folder by run.js.\n';
  fs.writeFileSync(path.join(__dirname, 'checkpoint.sql'), `${header}\n${parts.join('\n\n')}\n`);
}

async function main() {
  writeCheckpointFile();
  console.log('Starting a temporary MySQL server...');
  const server = await createDB({ dbName: 'university', logLevel: 'ERROR' });
  const conn = await mysql.createConnection({
    host: '127.0.0.1', port: server.port, user: server.username, database: server.dbName, dateStrings: true,
  });
  const [[{ v }]] = await conn.query('SELECT VERSION() AS v');

  const md = [
    '# Results',
    '',
    `Every statement from the \`sql/\` folder, run in order on **MySQL ${v}**, with the real output. This file is generated by \`run.js\`.`,
  ];
  let failures = 0;

  try {
    for (const file of FILES) {
      const expectErrors = file.startsWith('04');
      const sql = fs.readFileSync(path.join(__dirname, 'sql', file), 'utf8');
      md.push('', `## ${file}`, '');
      console.log(`\n=== ${file} ===`);

      for (const { label, expect, code } of statements(sql)) {
        let result;
        let error;
        try {
          [result] = await conn.query(code);
        } catch (e) {
          error = e;
        }

        const isQuery = Array.isArray(result);
        const showSql = file !== '01_schema.sql' || /^CREATE (TABLE|INDEX)/.test(code);

        if (expectErrors) {
          // It must fail, and with the RIGHT error (not some other problem)
          const ok = Boolean(error) && error.code === expect;
          if (!ok) failures++;
          const outcome = !error ? 'ACCEPTED (should have failed)' : error.code;
          console.log(`${ok ? '✅' : '❌'} ${label}  →  ${outcome}${ok ? '' : ` (expected ${expect})`}`);
          md.push(`**${label}**`, '', '```sql', code, '```', '',
            ok
              ? `✅ Rejected as expected: \`${error.code}\`: ${error.message}`
              : `❌ Expected \`${expect}\` but got: ${outcome}`, '');
          continue;
        }

        if (error) {
          failures++;
          console.log(`❌ ${label || code.slice(0, 60)}\n   ${error.message}`);
          md.push(`**${label}**`, '', '```sql', code, '```', '', `❌ Error: ${error.message}`, '');
          continue;
        }

        if (isQuery) {
          console.log(`\n${label}`);
          console.table(result);
          md.push(`**${label}**`, '', '```sql', code, '```', '', markdownTable(result), '');
        } else if (showSql) {
          const what = /^CREATE TABLE (\w+)/.exec(code)?.[1];
          if (file === '01_schema.sql') {
            console.log(`created ${what ? `table ${what}` : 'index'}`);
            md.push('```sql', code, '```', '', `✅ ${what ? `Table \`${what}\` created` : 'Index created'}`, '');
          } else {
            console.log(`${label || code.split('\n')[0]}  →  ${result.affectedRows} row(s) affected`);
            md.push(...(label ? [`**${label}**`, ''] : []), '```sql', code, '```', '', `✅ ${result.affectedRows} row(s) affected`, '');
          }
        }
      }
    }

    fs.writeFileSync(path.join(__dirname, 'results.md'), md.join('\n'));
    console.log(`\nSaved results.md${failures ? `, with ${failures} problem(s)!` : ', everything behaved as expected.'}`);
  } finally {
    await conn.end();
    await server.stop();
  }
  if (failures) process.exitCode = 1;
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
